// avmplus' libraries, embedded in the packages that load them when given
// none: builtin.abc in @swf2es/runtime, which every AS3 runtime loads
// first, and shell_toplevel.abc in @swf2es/cli, which `swf2es run` loads
// after it, as avmshell does. Each is the avmplus submodule's generated/
// file as base64, in a module of its own under the MPL-2.0, as avmplus'
// files stay apart from swf2es's Apache-2.0 ones.
//
//   node tools/avmplus-libraries.ts [--update]
//
// fails if a module does not hold its file's bytes; --update writes them.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const AVMPLUS = "https://github.com/swf2es/avmplus";

interface Library {
  /** The file's name in oracle/avmplus/generated/, without .abc. */
  abc: string;
  /** The constant the module exports. */
  constant: string;
  module: string;
  /** Its ActionScript in avmplus, and the script that compiles it. */
  source: string;
  script: string;
  what: string;
}

export const LIBRARIES: Library[] = [
  {
    abc: "builtin",
    constant: "builtinLibrary",
    module: "packages/runtime/src/avm2/builtin-library.ts",
    source: "core/",
    script: "core/builtin.py",
    what: "ActionScript 3's standard library, which every runtime loads first",
  },
  {
    abc: "shell_toplevel",
    constant: "shellToplevelLibrary",
    module: "packages/cli/src/shell-toplevel-library.ts",
    source: "shell/ and extensions/ (Sampler.as, Trace.as)",
    script: "shell/shell_toplevel.py",
    what: "avmshell's own classes, which `swf2es run` loads after builtin",
  },
];

/** The submodule's ABC for `library`, as the module is to hold it. */
export function abcOf(library: Library): Uint8Array {
  return new Uint8Array(readFileSync(join(root, `oracle/avmplus/generated/${library.abc}.abc`)));
}

/** The commit the submodule is checked out at, which the bytes are read from. */
function avmplusCommit(): string {
  return execFileSync("git", ["rev-parse", "HEAD"], {
    cwd: join(root, "oracle/avmplus"),
    encoding: "utf8",
  }).trim();
}

function generated(library: Library, abc: Uint8Array, commit: string): string {
  return `// avmplus' ${library.abc}.abc: ${library.what}.
// Generated by tools/avmplus-libraries.ts --update; not to be edited.
//
// This Source Code Form is subject to the terms of the Mozilla Public
// License, v. 2.0. If a copy of the MPL was not distributed with this
// file, You can obtain one at http://mozilla.org/MPL/2.0/.
//
// Its source form is the ActionScript in ${library.source}
// of avmplus, ${AVMPLUS} at commit
// ${commit},
// which ${library.script} compiles into generated/${library.abc}.abc.

declare function atob(data: string): string;

/** Base64 to bytes with a plain loop: Uint8Array.from with a callback takes some 8 times as long. */
function decode(text: string): Uint8Array {
  const raw = atob(text);
  const bytes = new Uint8Array(raw.length);
  for (let i = 0; i < raw.length; i++) {
    bytes[i] = raw.charCodeAt(i);
  }

  return bytes;
}

export const ${library.constant}: Uint8Array = decode(
  "${Buffer.from(abc).toString("base64")}",
);
`;
}

/** The base64 a generated module holds, as bytes. */
export function embedded(source: string): Uint8Array {
  const match = source.match(/decode\(\s*"([A-Za-z0-9+/=]*)"/);
  return new Uint8Array(match ? Buffer.from(match[1], "base64") : []);
}

if (import.meta.main) {
  const update = process.argv.includes("--update");
  const commit = update ? avmplusCommit() : "";
  let stale = 0;
  for (const library of LIBRARIES) {
    const abc = abcOf(library);
    const path = join(root, library.module);
    if (update) {
      writeFileSync(path, generated(library, abc, commit));
      console.log(`${library.module}: ${library.abc}.abc, ${abc.length} bytes, avmplus ${commit}`);
    } else if (!Buffer.from(embedded(readFileSync(path, "utf8"))).equals(abc)) {
      console.error(`${library.module} is not oracle/avmplus/generated/${library.abc}.abc`);
      stale++;
    }
  }

  if (stale > 0) {
    console.error("run node tools/avmplus-libraries.ts --update");
    process.exit(1);
  }
}
