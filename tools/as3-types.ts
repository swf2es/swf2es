// TypeScript declarations of the libraries' classes, for natives to read
// AS3 objects by (docs/architecture/runtime.md, "AS3 classes in
// TypeScript"): builtin.abc's into @swf2es/runtime, the player's
// playerglobal and AIR library into @swf2es/player.
//
//   node tools/as3-types.ts [--update]
//
// says which of the files the libraries' ABCs, as committed, no longer
// give, and exits 1 if any; --update writes them. pnpm as3:playerglobal,
// pnpm as3:air and tools/avmplus-libraries.ts --update run it after
// writing a library, and a unit test holds the files to the libraries.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { as3Declarations, type DeclaredLibrary } from "../packages/cli/src/as3-types.ts";
import { airLibrary } from "../packages/player/src/playerglobal/air-library.ts";
import { playerglobalLibrary } from "../packages/player/src/playerglobal/playerglobal-library.ts";
import { builtinLibrary } from "../packages/runtime/src/avm2/builtin-library.ts";
import { namesFrom } from "./abc-surface/as3.ts";
import { readSurface } from "./abc-surface/read.ts";

const root = fileURLToPath(new URL("../", import.meta.url));

/** Parameter names from the AS3 sources under `dir`, a file per class by package, as the ABC has none. */
function sourceNames(dir: string) {
  const files = new Map<string, Map<string, string[]>>();
  return (qualified: string, method: string): string[] | undefined => {
    let names = files.get(qualified);
    if (!names) {
      const at = qualified.lastIndexOf("::");
      names = namesFrom(
        join(root, dir),
        qualified.slice(0, Math.max(at, 0)),
        qualified.slice(at + 2),
      );
      files.set(qualified, names);
    }

    return names.get(method);
  };
}

function header(what: string, from: string, ...notice: string[]): string[] {
  return [
    `TypeScript declarations of ${what}'s classes: each one's public`,
    "members, as natives reach them through Runtime.prop, setProp and callProp.",
    "Generated by tools/as3-types.ts --update, not to be edited, from",
    `${from}.`,
    ...(notice.length ? ["", ...notice] : []),
  ];
}

/** Each declarations file, as [path from the repository's root, contents]. */
export function declarations(): [string, string][] {
  const builtin = [readSurface(builtinLibrary)];
  const playerglobal = [readSurface(playerglobalLibrary)];
  const air = [readSurface(airLibrary)];
  const builtinClasses: DeclaredLibrary = { abcs: builtin, classes: "avm2.BuiltinClasses" };
  const playerglobalClasses: DeclaredLibrary = {
    abcs: playerglobal,
    classes: "PlayerglobalClasses",
  };
  const player = {
    imports: ['import type { avm2 } from "@swf2es/runtime";'],
    ref: "avm2.Ref",
    value: "avm2.Value",
  };
  return [
    [
      "packages/runtime/src/avm2/builtin-types.generated.ts",
      as3Declarations({
        abcs: builtin,
        name: "Builtin",
        libraries: [],
        header: header(
          "avmplus' builtin.abc",
          "builtin-library.ts",
          "They describe avmplus' API, and are under its licence:",
          "This Source Code Form is subject to the terms of the Mozilla Public",
          "License, v. 2.0. If a copy of the MPL was not distributed with this",
          "file, You can obtain one at http://mozilla.org/MPL/2.0/.",
        ),
        imports: [
          'import type { Ref } from "./as3-types.js";',
          'import type { Value } from "./descriptors.js";',
        ],
        ref: "Ref",
        value: "Value",
      }),
    ],
    [
      "packages/player/src/playerglobal/playerglobal-types.generated.ts",
      as3Declarations({
        abcs: playerglobal,
        name: "Playerglobal",
        libraries: [builtinClasses],
        header: header(
          "the player's playerglobal",
          "playerglobal-library.ts and as3/playerglobal/src's parameter names",
          "Many of those names are Ruffle's (https://github.com/ruffle-rs/ruffle),",
          "under the MIT license or the Apache License 2.0: Copyright (c) 2018-2022",
          "Ruffle LLC and Ruffle contributors.",
        ),
        ...player,
        paramNames: sourceNames("as3/playerglobal/src"),
      }),
    ],
    [
      "packages/player/src/playerglobal/air-types.generated.ts",
      as3Declarations({
        abcs: air,
        name: "Air",
        libraries: [builtinClasses, playerglobalClasses],
        header: header("the player's AIR library", "air-library.ts and as3/air/src"),
        ...player,
        imports: [
          ...player.imports,
          'import type { PlayerglobalClasses } from "./playerglobal-types.generated.js";',
        ],
        paramNames: sourceNames("as3/air/src"),
      }),
    ],
  ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const update = process.argv.includes("--update");
  let stale = 0;
  for (const [path, text] of declarations()) {
    let old: string | null = null;
    try {
      old = readFileSync(join(root, path), "utf8");
    } catch {}

    if (old === text) {
      continue;
    }

    if (update) {
      writeFileSync(join(root, path), text);
      console.log(`wrote ${path}`);
    } else {
      console.log(`${path} is stale`);
      stale++;
    }
  }

  if (stale) {
    console.log("run node tools/as3-types.ts --update");
    process.exitCode = 1;
  }
}
