import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { findZig, ZIG_VERSION } from "../../tools/zig.ts";

const here = fileURLToPath(new URL(".", import.meta.url));
const digest = createHash("sha256").update(ZIG_VERSION);
for (const file of ["build.ts", "build.zig", "src/bitmap.zig"]) {
  digest.update(readFileSync(join(here, file)));
}

const inputDigest = digest.digest("hex");
const target = join(here, "src/binary.ts");
if (process.argv.includes("--check")) {
  if (!readFileSync(target, "utf8").includes(`inputs: ${inputDigest}`)) {
    throw new Error("native inputs changed; run pnpm --filter @swf2es/native build:wasm");
  }
} else {
  const work = mkdtempSync(join(tmpdir(), "swf2es-native-"));
  try {
    execFileSync(findZig(), ["build", "--prefix", work], {
      cwd: here,
      stdio: "inherit",
      env: {
        ...process.env,
        ZIG_LOCAL_CACHE_DIR: join(work, "cache"),
        ZIG_GLOBAL_CACHE_DIR: join(work, "global"),
      },
    });
    const binaries: string[] = [];
    for (const name of ["scalar", "simd"]) {
      const bytes = readFileSync(join(work, `bin/${name}.wasm`));
      const imports = WebAssembly.Module.imports(await WebAssembly.compile(bytes));
      if (imports.length !== 0) {
        throw new Error(`unexpected native imports: ${JSON.stringify(imports)}`);
      }

      binaries.push(`export const ${name} =\n  "${bytes.toString("base64")}";\n`);
      console.log(`native ${name}: ${bytes.length} bytes`);
    }

    writeFileSync(
      target,
      `// Generated by packages/native/build.ts.\n// inputs: ${inputDigest}\n${binaries.join("\n")}`,
    );
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}
