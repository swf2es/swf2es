// swf2es types: TypeScript declarations of the classes a SWF's or an ABC's
// code defines (as3-types.ts), extending those of the libraries the player
// links it against, for a host or a native to reach its objects by.
import { writeFile } from "node:fs/promises";
import { basename } from "node:path";
import { parseArgs } from "node:util";
import { type AbcSurface, readAbcSurface } from "@swf2es/format";
import { airLibrary, builtinLibrary, playerglobalLibrary } from "@swf2es/player/libraries";
import { InputError, readInput } from "../aot.js";
import { COMMON_OPTIONS, COMMON_USAGE, type Command, parse } from "../args.js";
import { as3Declarations } from "../as3-types.js";
import { read, writing } from "../files.js";
import { fail, usageError } from "../output.js";

const USAGE = `usage: swf2es types <file.swf|file.abc> [options]

Writes TypeScript declarations of the classes a SWF's ABCs (its DoABC and
DoABC2 tags) or a bare ABC define: for each class, an interface of its
instances' public members and one of its class object's (statics), keyed
by qualified name in Classes and Statics, for @swf2es/runtime's
Runtime.prop, setProp and callProp. A class extends the declarations of
the one it extends in the libraries the player loads, builtin.abc and
the player's playerglobal (@swf2es/player/as3-types); a type that none
defines is avm2.Value.

options:
  -o, --out <file>     where to write (default: standard output)
  --name <prefix>      the maps' names' prefix: <prefix>Classes and
                       <prefix>Statics (default: none)
  --air                resolve types against AIR's library too, as the
                       player links an AIR application's SWF
${COMMON_USAGE}

exit status: 0 on success, 2 for a mistake in the command line, 1 for
anything else (an unreadable, malformed or AVM1 input, or an output that
cannot be written)`;

const OPTIONS = {
  out: { type: "string", short: "o" },
  name: { type: "string" },
  air: { type: "boolean" },
  ...COMMON_OPTIONS,
} as const;

function surfaceOf(abc: Uint8Array, what: string): AbcSurface {
  try {
    return readAbcSurface(abc);
  } catch (e) {
    fail(`${what}: a malformed ABC (${(e as Error).message})`);
  }
}

export const types: Command = {
  name: "types",
  summary: "write TypeScript declarations of a SWF's or an ABC's classes",
  usage: USAGE,
  async main(argv) {
    const parsed = parse(types, () =>
      parseArgs({ args: argv, allowPositionals: true, options: OPTIONS }),
    );
    if (!parsed) {
      return;
    }

    const { values, positionals } = parsed;
    if (positionals.length !== 1) {
      usageError(`expected one input file, got ${positionals.length}`, "types");
    }

    const name = values.name ?? "";
    if (name && !/^[A-Za-z_$][\w$]*$/.test(name)) {
      usageError(`--name ${name} is not an identifier`, "types");
    }

    const file = positionals[0];
    let input: ReturnType<typeof readInput>;
    try {
      input = readInput(await read(file, "input"));
    } catch (e) {
      fail(e instanceof InputError ? `${file}: ${e.message}` : String((e as Error).stack ?? e));
    }

    if (input.avm1) {
      fail(`${file} is an AVM1 SWF, which defines no classes`);
    }

    const abcs = input.abcs.map((a, i) => surfaceOf(a.abc, `${file}, ABC ${i}`));
    const libraries = [builtinLibrary, playerglobalLibrary, ...(values.air ? [airLibrary] : [])];
    const text = as3Declarations({
      abcs,
      name,
      libraries: [{ abcs: libraries.map((l) => surfaceOf(l, "a library")), classes: "As3Classes" }],
      header: [
        `TypeScript declarations of ${basename(file)}'s classes: each one's public`,
        "members, for @swf2es/runtime's Runtime.prop, setProp and callProp.",
        `Generated by swf2es types${values.air ? " --air" : ""}.`,
      ],
      imports: [
        'import type { As3Classes } from "@swf2es/player/as3-types";',
        'import type { avm2 } from "@swf2es/runtime";',
      ],
      ref: "avm2.Ref",
      value: "avm2.Value",
    });

    const out = values.out;
    if (out === undefined) {
      process.stdout.write(text);
      return;
    }

    await writing(out, () => writeFile(out, text));
  },
};
