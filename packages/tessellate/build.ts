import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  copyFileSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { findZig, ZIG_VERSION } from "../../tools/zig.ts";

const here = fileURLToPath(new URL(".", import.meta.url));
const vendor = fileURLToPath(new URL("../../vendor/libtess2/", import.meta.url));
const cFiles = (dir: string) =>
  readdirSync(dir)
    .filter((name) => /\.[ch]$/.test(name))
    .sort()
    .map((name) => join(dir, name));
const inputs = [
  fileURLToPath(import.meta.url),
  join(here, "src/wrapper.c"),
  ...cFiles(join(here, "include")),
  ...cFiles(join(vendor, "Include")),
  ...cFiles(join(vendor, "Source")),
  join(vendor, "LICENSE.txt"),
];
const digest = createHash("sha256").update(ZIG_VERSION);
for (const file of inputs) {
  digest.update(readFileSync(file));
}

const inputDigest = digest.digest("hex");
const target = join(here, "src/binary.ts");
if (process.argv.includes("--check")) {
  if (!readFileSync(target, "utf8").includes(`inputs: ${inputDigest}`)) {
    throw new Error("tessellation inputs changed; run pnpm --filter @swf2es/tessellate build:wasm");
  }
} else {
  const work = mkdtempSync(join(tmpdir(), "swf2es-tessellate-"));
  try {
    const symbols = [
      "reset",
      "alloc",
      "run",
      "vertices",
      "indices",
      "vertexCount",
      "triangleCount",
      "highWater",
      "allocated",
      "setLimit",
    ];
    execFileSync(
      findZig(),
      [
        "cc",
        "-target",
        "wasm32-freestanding",
        "-O2",
        "-DNDEBUG",
        "-nostdlib",
        "-mbulk-memory",
        `-I${join(here, "include")}`,
        `-I${join(vendor, "Include")}`,
        "-Wl,--no-entry",
        "-Wl,-z,stack-size=262144",
        "-Wl,--export-memory",
        "-Wl,--strip-all",
        "-Wl,--max-memory=134217728",
        ...symbols.map((name) => `-Wl,--export=${name}`),
        join(here, "src/wrapper.c"),
        ...cFiles(join(vendor, "Source")).filter((file) => file.endsWith(".c")),
        "-o",
        join(work, "tessellate.wasm"),
      ],
      {
        stdio: "inherit",
        env: {
          ...process.env,
          ZIG_LOCAL_CACHE_DIR: join(work, "cache"),
          ZIG_GLOBAL_CACHE_DIR: join(work, "global"),
        },
      },
    );
    const bytes = readFileSync(join(work, "tessellate.wasm"));
    const imports = WebAssembly.Module.imports(await WebAssembly.compile(bytes));
    if (
      JSON.stringify(imports) !==
      JSON.stringify([{ module: "env", name: "failure", kind: "function" }])
    ) {
      throw new Error(`unexpected tessellation imports: ${JSON.stringify(imports)}`);
    }

    writeFileSync(
      target,
      `// Generated by packages/tessellate/build.ts; libtess2 is under SGI Free Software License B.\n// inputs: ${inputDigest}\nexport const binary =\n  "${bytes.toString("base64")}";\n`,
    );
    copyFileSync(join(vendor, "LICENSE.txt"), join(here, "LICENSE.libtess2"));
    console.log(`tessellate: ${bytes.length} bytes`);
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}
