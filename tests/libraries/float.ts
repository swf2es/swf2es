// The scalar AIR primitive declared using ASC's ordinary class syntax, so
// its metadata can be loaded beside the Flash builtins without float opcodes.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { runOracle } from "../../oracle/oracle.ts";
import { markPublic } from "../player/air-library.ts";

const root = fileURLToPath(new URL("../../", import.meta.url));
export const GENERATED = `${root}packages/runtime/src/avm2/float-library.ts`;

export function compileFloatLibrary(): Uint8Array {
  const out = `${root}tests/libraries/out/float/`;
  const [result] = runOracle([{ source: `${root}as3/builtin/src/float.as` }], out, {
    imports: ["builtin"],
    run: false,
  });
  if (!result.compiled) {
    throw new Error(`the float library did not compile:\n${result.compileLog}`);
  }

  return markPublic(new Uint8Array(readFileSync(`${out}${result.name}.abc`)));
}

export function generated(abc: Uint8Array): string {
  const rows: string[] = [];
  for (let i = 0; i < abc.length; i += 24) {
    rows.push(`  ${Array.from(abc.subarray(i, i + 24)).join(", ")},`);
  }

  return `// Generated from as3/builtin/src/float.as by tests/libraries/float.ts.
// Load after builtin.abc, as a builtin, to expose AIR's scalar float type.
// biome-ignore format: preserve the generated byte table.
export const floatLibrary: Uint8Array = new Uint8Array([
${rows.join("\n")}
]);
`;
}

if (import.meta.main) {
  const text = generated(compileFloatLibrary());
  if (process.argv.includes("--update")) {
    writeFileSync(GENERATED, text);
  } else if (readFileSync(GENERATED, "utf8") !== text) {
    throw new Error(`${GENERATED} is out of date: run with --update`);
  }
}
